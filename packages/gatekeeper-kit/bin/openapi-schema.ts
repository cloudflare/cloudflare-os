#!/usr/bin/env node
/// <reference types="node" />

// Generates type-only schemas for `@gadgets/gatekeeper-kit/http` from an OpenAPI document, with the
// Forge plugin in ../forge: one `index.d.ts` with the models and an `Api` schema of every operation,
// or with --group-by tag, one `.d.ts` per tag, each with that group's models and schema.
//
//     gatekeeper-openapi-schema <spec> --out <dir> [--sha256 <hex>] [--group-by tag]
//                               [--operations <file>] [--omit-header <name>]...
//                               [--writable <property>]... [--patch <file>]
//                               [--scopes-extension <name>]
//
// <spec> is a JSON file or an https URL. --sha256 is the document's SHA-256, which a URL needs, so
// that a run generates from the same document as the last one. --operations names a JSON Lines
// file of the operations to keep, each line an object as --list prints one; every other operation
// is left out. Only a line's `operationId` chooses. The run fails for a line whose `method` or
// `path` is no longer the document's, and if the schemas cannot hold one that is listed. --group-by tag
// groups each operation by its first tag, where one schema of every operation is too large.
// --omit-header drops a header parameter, by name in any case, from every operation: one the
// client sends itself, through its `headers` or `fetch` option, so calls need not pass it.
// --writable clears `readOnly` from every property of that name, for a document that marks a field
// read-only although requests send it, such as an `id` that references must name. --patch applies a
// JSON Patch (RFC 6902) file of `add`, `replace` and `remove` operations to the document first, to
// correct what it gets wrong; each operation says why in a `reason`. Each operation's comment names
// the scopes its `security` declares; --scopes-extension names an extension to read them from
// instead, for a document that keeps them in one, such as PagerDuty's `x-pd-requires-scope`.
// The output directory holds only generated files: they are replaced on each run, and a file in it
// that Forge did not write stops the run.
//
//     gatekeeper-openapi-schema <spec> --list [--sha256 <hex>] [--patch <file>]
//
// prints every operation of the document instead, as JSON Lines: one object per operation with its
// `operationId`, `method`, `path`, first `tag` and `summary`. The lines chosen from it are the
// --operations file.

import { spawn, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { once } from "node:events";
import {
  existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, renameSync, rmSync,
} from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, resolve } from "node:path";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const GENERATED_PREAMBLE = "// Code generated by forge. DO NOT EDIT.";
const HTTP_METHODS = ["get", "put", "post", "delete", "options", "head", "patch", "trace"];

const usage = "usage: gatekeeper-openapi-schema <spec> --out <dir> [--sha256 <hex>] [--group-by tag] " +
  "[--operations <file>] [--omit-header <name>]... [--writable <property>]... [--patch <file>] " +
  "[--scopes-extension <name>]\n" +
  "       gatekeeper-openapi-schema <spec> --list [--sha256 <hex>] [--patch <file>]";

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };
type JsonObject = { [key: string]: Json };

function fail(message: string): never {
  process.stderr.write(`gatekeeper-openapi-schema: ${message}\n`);
  process.exit(1);
}

function isObject(value: Json | undefined): value is JsonObject {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

const { values, positionals } = (() => {
  try {
    return parseArgs({
      allowPositionals: true,
      options: {
        out: { type: "string" },
        list: { type: "boolean" },
        sha256: { type: "string" },
        "group-by": { type: "string" },
        operations: { type: "string" },
        "omit-header": { type: "string", multiple: true },
        writable: { type: "string", multiple: true },
        patch: { type: "string" },
        "scopes-extension": { type: "string" },
      },
    });
  } catch (error) {
    fail(`${(error as Error).message}\n${usage}`);
  }
})();
if (positionals.length !== 1 || (values.out === undefined) !== (values.list === true)) fail(usage);
if (values["group-by"] !== undefined && values["group-by"] !== "tag") {
  fail(`--group-by takes only "tag"\n${usage}`);
}

const kitDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const forgeDir = dirname(createRequire(import.meta.url).resolve("@cloudflare/forge/package.json"));

if (values.out === undefined) {
  await list(positionals[0], values.sha256, values.patch);
} else {
  await main(positionals[0], values.out, values.sha256, values["group-by"] === "tag", values.operations,
    values["omit-header"] ?? [], values.writable ?? [], values.patch, values["scopes-extension"]);
}

/** Prints each operation of the document as a line of JSON, sorted by path. */
async function list(spec: string, sha256: string | undefined, patchFile: string | undefined): Promise<void> {
  const doc = await load(spec, sha256, patchFile);
  const text = (value: Json | undefined) => (typeof value === "string" ? value.replace(/\s+/g, " ").trim() : "");
  const lines = [...operations(doc)]
    .toSorted(([, , , a], [, , , b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([, method, operation, path]) => JSON.stringify({
      // As written: the id is what an --operations file chooses by.
      operationId: typeof operation.operationId === "string" ? operation.operationId : "", method: method.toUpperCase(), path,
      tag: text(Array.isArray(operation.tags) ? operation.tags[0] : undefined), summary: text(operation.summary),
    }));
  process.stdout.write(`${lines.join("\n")}\n`);
}

async function main(
  spec: string, outArg: string, sha256: string | undefined, byTag: boolean,
  operationsFile: string | undefined, omittedHeaders: readonly string[], writable: readonly string[],
  patchFile: string | undefined, scopesExtension: string | undefined,
): Promise<void> {
  const doc = await load(spec, sha256, patchFile);
  if (operationsFile !== undefined) keepOperations(doc, readOperations(operationsFile), operationsFile);
  prepareOperations(doc, byTag, scopesExtension);
  omitHeaders(doc, new Set(omittedHeaders.map(name => name.toLowerCase())));
  inlineInnerRefs(doc);
  clearReadOnly(doc, new Set(writable));
  renameCollidingProperties(doc);

  const wasm = buildPlugin();
  const outDir = resolve(outArg);
  // Beside the output, so the finished directory moves into place with a rename.
  mkdirSync(dirname(outDir), { recursive: true });
  const stagingDir = mkdtempSync(join(dirname(outDir), ".openapi-schema-"));
  // On exit, because a failed run exits where it fails.
  process.once("exit", () => rmSync(stagingDir, { recursive: true, force: true }));
  await runForge(doc, wasm, stagingDir);
  checkOperations(doc, stagingDir, operationsFile);
  replaceOutput(stagingDir, outDir);
  process.stderr.write(`gatekeeper-openapi-schema: wrote ${relative(process.cwd(), outDir) || "."}\n`);
}

async function readDocument(spec: string, sha256: string | undefined): Promise<JsonObject> {
  let text: string;
  if (spec.startsWith("https://")) {
    // What a URL serves can change, and a regeneration must change only what its author changed.
    if (sha256 === undefined) fail(`a URL needs --sha256, the SHA-256 of the document it serves\n${usage}`);
    const response = await fetch(spec);
    if (!response.ok) fail(`fetching ${spec} failed with status ${response.status}`);
    text = await response.text();
  } else {
    text = readFileSync(spec, "utf8");
  }
  const actual = createHash("sha256").update(text).digest("hex");
  if (sha256 !== undefined && sha256.toLowerCase() !== actual) {
    fail(`${spec} has SHA-256 ${actual}, not ${sha256}`);
  }
  const parsed = JSON.parse(text) as Json;
  if (!isObject(parsed) || !isObject(parsed.paths)) fail(`${spec} is not an OpenAPI document`);
  return parsed;
}

/**
 * The document every step works on: read, then patched, then with its referenced path items
 * copied in. In that order, so that a patch to a referenced path item reaches the copy.
 */
async function load(spec: string, sha256: string | undefined, patchFile: string | undefined): Promise<JsonObject> {
  const document = await readDocument(spec, sha256);
  if (patchFile !== undefined) applyPatch(document, JSON.parse(readFileSync(patchFile, "utf8")) as Json, patchFile);
  inlinePathItems(document);
  return document;
}

/** What the JSON Pointer of `ref`, a `$ref` into `document`, names. */
function pointee(document: JsonObject, ref: string): Json | undefined {
  let value: Json | undefined = document;
  for (const segment of ref.slice(2).split("/")) {
    const key = segment.replaceAll("~1", "/").replaceAll("~0", "~");
    value = Array.isArray(value) ? value[Number(key)] : isObject(value) ? value[key] : undefined;
  }
  return value;
}

/**
 * Replaces each path item that is a `$ref` with a copy of the one it names, so that every step
 * that reads a path's operations finds them. Forge follows such a `$ref`; nothing here would.
 */
function inlinePathItems(document: JsonObject): void {
  const paths = document.paths as JsonObject;
  for (const [path, item] of Object.entries(paths)) {
    if (!isObject(item) || typeof item.$ref !== "string") continue;
    const { $ref, ...own } = item;
    const named = $ref.startsWith("#/") ? pointee(document, $ref) : undefined;
    if (!isObject(named) || "$ref" in named) fail(`${path} is a $ref to "${$ref}", which is not a path item of the document`);
    paths[path] = { ...structuredClone(named), ...own };
  }
}

/**
 * Applies a JSON Patch (RFC 6902) to `document`: its `add`, `replace` and `remove` operations, in
 * order. Any other operation, or a path that does not resolve, stops the run.
 */
function applyPatch(document: JsonObject, patch: Json, file: string): void {
  if (!Array.isArray(patch)) fail(`${file} is not a JSON Patch: an array of operations`);
  patch.forEach((operation, index) => {
    const where = `${file} operation ${index}`;
    if (!isObject(operation) || typeof operation.op !== "string" || typeof operation.path !== "string") {
      fail(`${where} needs an op and a path`);
    }
    if (typeof operation.reason !== "string" || operation.reason.trim() === "") {
      fail(`${where} needs a reason: what the document gets wrong, and what shows it`);
    }
    const { op, path } = operation;
    if (!path.startsWith("/")) fail(`${where}: path ${path} is not a JSON Pointer to a member`);
    const keys = path.slice(1).split("/").map(key => key.replaceAll("~1", "/").replaceAll("~0", "~"));
    const last = keys.pop()!;
    let parent: Json | undefined = document;
    for (const key of keys) {
      parent = Array.isArray(parent) ? parent[Number(key)] : isObject(parent) ? parent[key] : undefined;
    }
    if (!Array.isArray(parent) && !isObject(parent)) fail(`${where}: nothing at ${path}'s parent`);
    const exists = Array.isArray(parent) ? Number(last) < parent.length : Object.hasOwn(parent, last);
    if (op !== "add" && !exists) fail(`${where}: nothing at ${path} to ${op}`);
    if (op !== "remove" && !("value" in operation)) fail(`${where} needs a value`);
    if (op !== "add" && op !== "replace" && op !== "remove") fail(`${where}: op ${op} is not add, replace or remove`);
    if (Array.isArray(parent)) {
      const at = last === "-" ? parent.length : Number(last);
      if (!Number.isInteger(at) || at < 0 || at > parent.length) fail(`${where}: ${path} is not an index`);
      if (op === "add") parent.splice(at, 0, operation.value!);
      else if (op === "replace") parent[at] = operation.value!;
      else parent.splice(at, 1);
    } else if (op === "remove") {
      delete parent[last];
    } else {
      parent[last] = operation.value!;
    }
  });
}

/** The operations an --operations file lists, by operationId: each line as --list printed it. */
function readOperations(file: string): Map<string, JsonObject> {
  const listed = new Map<string, JsonObject>();
  readFileSync(file, "utf8").split("\n").forEach((line, index) => {
    if (line.trim() === "") return;
    let operation: Json;
    try {
      operation = JSON.parse(line) as Json;
    } catch {
      fail(`${file} line ${index + 1} is not JSON: each line is one operation, as --list prints it`);
    }
    if (!isObject(operation) || typeof operation.operationId !== "string" || operation.operationId === "") {
      fail(`${file} line ${index + 1} needs an operationId`);
    }
    listed.set(operation.operationId, operation);
  });
  return listed;
}

/** Each operation in the document, with the path item and method holding it, and its path. */
function* operations(document: JsonObject): Generator<[JsonObject, string, JsonObject, string]> {
  for (const [path, item] of Object.entries(document.paths as JsonObject)) {
    if (!isObject(item)) continue;
    for (const method of HTTP_METHODS) {
      const operation = item[method];
      if (isObject(operation)) yield [item, method, operation, path];
    }
  }
}

/**
 * Removes every operation `listed` does not name. Fails on an id the document lacks, and on a line
 * whose `method` or `path` is not the document's: the operation moved since the line was chosen.
 */
function keepOperations(document: JsonObject, listed: Map<string, JsonObject>, file: string): void {
  const found = new Set<string>();
  const moved: string[] = [];
  for (const [item, method, operation, path] of operations(document)) {
    const line = typeof operation.operationId === "string" ? listed.get(operation.operationId) : undefined;
    if (line === undefined) {
      delete item[method];
      continue;
    }
    found.add(operation.operationId as string);
    const says = `${line.method ?? method.toUpperCase()} ${line.path ?? path}`;
    if (says !== `${method.toUpperCase()} ${path}`) {
      moved.push(`${operation.operationId} is ${method.toUpperCase()} ${path} in the document, not ${says} as ${file} says`);
    }
  }
  if (moved.length > 0) fail(moved.join("\n"));
  const missing = [...listed.keys()].filter(id => !found.has(id));
  if (missing.length > 0) fail(`the document has no operation ${missing.join(", ")}`);
  const paths = document.paths as JsonObject;
  for (const [path, item] of Object.entries(paths)) {
    if (isObject(item) && !HTTP_METHODS.some(method => method in item)) delete paths[path];
  }
}

/**
 * Copies each operationId into `x-operation-id`, which Forge hands the plugin for its comments,
 * and puts every operation in one group, or with `byTag`, in the group of its first tag. Removes
 * `x-forge-aliases`, a second name for an SDK method, because Forge hands the plugin no method for
 * an operation that has one.
 */
function prepareOperations(document: JsonObject, byTag: boolean, scopesExtension: string | undefined): void {
  let count = 0;
  for (const [, method, operation] of operations(document)) {
    delete operation["x-forge-aliases"];
    const id = operation.operationId;
    if (typeof id === "string") operation["x-operation-id"] = id;
    const scopes = declaredScopes(document, operation, scopesExtension);
    if (scopes !== "") operation["x-declared-scopes"] = scopes;
    if (!byTag) {
      // Forge would read groups from the dots of an operationId. The schema never shows this name.
      delete operation["x-forge-group-name"];
      operation["x-forge-method-name"] = `operation${count++}`;
      continue;
    }
    if ("x-forge-method-name" in operation) continue;
    const tag = Array.isArray(operation.tags) ? operation.tags[0] : undefined;
    if (typeof tag !== "string") continue;
    operation["x-forge-group-name"] = tag;
    operation["x-forge-method-name"] = typeof id === "string" ? id : method;
  }
}

/**
 * The scopes the document declares for `operation`, as the plugin prints them in its comment: from
 * `extension` when one is named, else from the operation's `security`, or the document's when it
 * has none. Scopes one requirement lists are all needed and are joined with commas; requirements
 * are alternatives and are joined with "or". Empty when none are declared.
 */
function declaredScopes(document: JsonObject, operation: JsonObject, extension: string | undefined): string {
  const code = (scopes: Json[]) => scopes.filter(scope => typeof scope === "string").map(scope => `\`${scope}\``).join(", ");
  if (extension !== undefined) {
    const value = operation[extension];
    return code(Array.isArray(value) ? value : [value ?? null]);
  }
  const security = operation.security ?? document.security;
  if (!Array.isArray(security)) return "";
  return security
    .map(requirement => code(isObject(requirement) ? Object.values(requirement).flat() : []))
    .filter(scopes => scopes !== "")
    .join(" or ");
}

/**
 * Removes the header parameters `names` names, lower-cased, from every operation and path item,
 * resolving parameters that refer to `components.parameters`.
 */
function omitHeaders(document: JsonObject, names: Set<string>): void {
  if (names.size === 0) return;
  const components = isObject(document.components) && isObject(document.components.parameters)
    ? document.components.parameters : {};
  const resolveRef = (parameter: Json): Json | undefined => {
    if (!isObject(parameter) || typeof parameter.$ref !== "string") return parameter;
    const prefix = "#/components/parameters/";
    if (!parameter.$ref.startsWith(prefix)) return undefined;
    return components[parameter.$ref.slice(prefix.length).replaceAll("~1", "/").replaceAll("~0", "~")];
  };
  const omitted = (parameter: Json): boolean => {
    const resolved = resolveRef(parameter);
    return isObject(resolved) && resolved.in === "header" && typeof resolved.name === "string" &&
      names.has(resolved.name.toLowerCase());
  };
  const owners = [...Object.values(document.paths as JsonObject).filter(isObject),
    ...[...operations(document)].map(([, , operation]) => operation)];
  for (const owner of owners) {
    if (Array.isArray(owner.parameters)) owner.parameters = owner.parameters.filter(p => !omitted(p));
  }
}

/** Clears `readOnly` from every property, in any schema, that `names` names. */
function clearReadOnly(value: Json, names: Set<string>): void {
  if (names.size === 0) return;
  if (Array.isArray(value)) {
    for (const item of value) clearReadOnly(item, names);
    return;
  }
  if (!isObject(value)) return;
  if (isObject(value.properties)) {
    for (const [name, property] of Object.entries(value.properties)) {
      if (names.has(name) && isObject(property)) delete property.readOnly;
    }
  }
  for (const item of Object.values(value)) clearReadOnly(item, names);
}

/** Whether `ref` points inside a component other than a schema, rather than at a whole one. */
function isInnerRef(ref: string): boolean {
  const segments = ref.split("/");
  return ref.startsWith("#/components/") && segments[2] !== "schemas" && segments.length > 4;
}

/**
 * Replaces each `$ref` to a part of a component other than a schema, such as
 * `#/components/responses/Conflict/content/application~1json/schema`, with a copy of what it
 * points to. Forge follows `$ref`s to whole components and into `components.schemas` only.
 */
function inlineInnerRefs(document: JsonObject): void {
  const inline = (value: Json, inlining: readonly string[]): Json => {
    if (Array.isArray(value)) return value.map(item => inline(item, inlining));
    if (!isObject(value)) return value;
    const ref = value.$ref;
    if (typeof ref === "string" && isInnerRef(ref)) {
      if (inlining.includes(ref)) fail(`$ref "${ref}" refers to itself`);
      const resolved = pointee(document, ref);
      if (resolved === undefined) fail(`$ref "${ref}" points to nothing`);
      return inline(structuredClone(resolved), [...inlining, ref]);
    }
    for (const [key, item] of Object.entries(value)) value[key] = inline(item, inlining);
    return value;
  };
  inline(document, []);
}

/**
 * Forge names a property by its words, which it reads from letters and digits, so `+1` and `-1`
 * are both `1` and collide. The plugin keys objects by wire name, so colliding properties are given
 * names Forge keeps apart: the hex of their wire names.
 */
function renameCollidingProperties(value: Json): void {
  if (Array.isArray(value)) {
    value.forEach(renameCollidingProperties);
    return;
  }
  if (!isObject(value)) return;
  const properties = value.properties;
  if (isObject(properties)) {
    const byWords = new Map<string, string[]>();
    for (const name of Object.keys(properties)) {
      const words = forgeWords(name);
      byWords.set(words, [...byWords.get(words) ?? [], name]);
    }
    for (const names of byWords.values()) {
      if (names.length < 2) continue;
      for (const name of names) {
        const property = properties[name];
        if (isObject(property) && !("x-forge-property-name" in property)) {
          property["x-forge-property-name"] = `p${Buffer.from(name).toString("hex")}`;
        }
      }
    }
  }
  Object.values(value).forEach(renameCollidingProperties);
}

/** Roughly the words Forge reads from a name: runs of letters and digits, split at camelCase. */
function forgeWords(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1 $2").toLowerCase()
    .split(/[^a-z0-9]+/).filter(Boolean).join(" ");
}

/** Builds the plugin component, unless one built from the same sources is cached. */
function buildPlugin(): string {
  const sources = ["forge/plugin.ts", "forge/emit.ts"].map(path => join(kitDir, path));
  const hash = createHash("sha256");
  for (const path of [...sources, join(forgeDir, "package.json")]) hash.update(readFileSync(path));
  const cacheDir = join(kitDir, "node_modules", ".cache", "openapi-schema");
  const wasm = join(cacheDir, `plugin-${hash.digest("hex").slice(0, 16)}.wasm`);
  if (existsSync(wasm)) return wasm;

  mkdirSync(cacheDir, { recursive: true });
  for (const stale of readdirSync(cacheDir)) rmSync(join(cacheDir, stale), { force: true });
  const result = spawnSync(process.execPath,
    [join(forgeDir, "bin", "forge-plugin.mjs"), "build", sources[0], "-o", wasm],
    { stdio: ["ignore", "inherit", "inherit"] });
  if (result.status !== 0 || !existsSync(wasm)) fail("building the Forge plugin failed");
  return wasm;
}

async function runForge(document: JsonObject, plugin: string, outDir: string): Promise<void> {
  const forge = spawn(process.execPath,
    [join(forgeDir, "bin", "forge.cjs"), "-", "--target", `wasm://${plugin}`, "--out", outDir],
    { stdio: ["pipe", "inherit", "inherit"] });
  const [[code], ] = await Promise.all([
    once(forge, "close") as Promise<[number | null]>,
    pipeline(Readable.from([JSON.stringify(document)]), forge.stdin),
  ]);
  if (code !== 0) fail(`forge exited with ${code}`);
}

/**
 * Fails unless the files in `dir` account for every operation of `document`: in a schema, or
 * named as left out. A listed operation must be in a schema, since its caller asked for it.
 */
function checkOperations(document: JsonObject, dir: string, operationsFile: string | undefined): void {
  // As forge/emit.ts prints them: a schema's `  get: [` and `      path: "…";`, and the left-out
  // list's ` * - GET /path (id): reason.`.
  const inSchema = new Set<string>();
  const leftOut = new Map<string, string>();
  for (const path of filesIn(dir)) {
    let verb = "";
    for (const line of readFileSync(path, "utf8").split("\n")) {
      verb = /^  (\w+): \[$/.exec(line)?.[1] ?? verb;
      const operation = /^      path: (".*");$/.exec(line);
      if (operation) inSchema.add(`${verb} ${JSON.parse(operation[1]) as string}`);
      const skipped = /^ \* - (\w+) (\S+)(?: \(.*\))?: (.*)$/.exec(line);
      if (skipped) leftOut.set(`${skipped[1].toLowerCase()} ${skipped[2]}`, skipped[3]);
    }
  }
  const problems: string[] = [];
  for (const [path, item] of Object.entries(document.paths as JsonObject)) {
    if (!isObject(item)) continue;
    for (const method of HTTP_METHODS) {
      const operation = item[method];
      if (!isObject(operation) || inSchema.has(`${method} ${path}`)) continue;
      const name = `${typeof operation.operationId === "string" ? `${operation.operationId}, ` : ""}` +
        `${method.toUpperCase()} ${path}`;
      const reason = leftOut.get(`${method} ${path}`);
      if (reason === undefined) {
        problems.push(`${name} is missing from the output, and Forge did not say why`);
      } else if (operationsFile !== undefined) {
        problems.push(`${name} cannot be in a schema: ${reason} Take it out of ${operationsFile} ` +
          "and write that call by hand");
      }
    }
  }
  if (problems.length > 0) fail(problems.join("\n"));
}

/** Replaces the generated files in `out` with those in `staging`. */
function replaceOutput(staging: string, out: string): void {
  if (existsSync(out)) {
    // Every entry the removal below deletes: a link or a socket is no more generated than a file.
    for (const entry of readdirSync(out, { recursive: true, withFileTypes: true })) {
      if (entry.isDirectory()) continue;
      const path = join(entry.parentPath, entry.name);
      if (!entry.isFile() || !readFileSync(path, "utf8").startsWith(GENERATED_PREAMBLE)) {
        fail(`${relative(process.cwd(), path)} was not generated; the output directory must hold ` +
          "only generated files");
      }
    }
    rmSync(out, { recursive: true });
  }
  renameSync(staging, out);
}

function filesIn(dir: string): string[] {
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter(entry => entry.isFile())
    .map(entry => join(entry.parentPath, entry.name));
}
