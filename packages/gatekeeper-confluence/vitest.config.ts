import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import capnwebValidate from "capnweb-validate/vite";
import { defineConfig } from "vitest/config";

export default defineConfig({
  plugins: [
    {
      // The Worker imports its `.txt` and `.svg` modules as text, as the deployed bundle's Text
      // rules do.
      name: "text-modules",
      enforce: "pre",
      load(id: string) {
        const path = id.split("?")[0];
        if (!/\.(txt|svg)$/.test(path)) return null;
        return `export default ${JSON.stringify(readFileSync(path, "utf8"))};`;
      },
    },
    // The configurator and the Worker's sessions carry `@validateRpc()`, applied in memory as in
    // the workerd project.
    capnwebValidate(),
  ],
  test: {
    include: ["__tests__/*.test.ts"],
    environment: "node",
    alias: [
      {
        // Lets modules that define a Durable Object or an `RpcTarget` be imported at all. See the
        // stub for what it does and does not provide.
        find: "cloudflare:workers",
        replacement: fileURLToPath(new URL("./__tests__/stubs/cloudflare-workers.ts", import.meta.url)),
      },
      {
        // The configurator frame is generated by `build:configurator`; the Worker only embeds it,
        // so tests that import the Worker don't need it built.
        find: /^\.\/generated\/confluence-configurator-ui\.txt$/,
        replacement: fileURLToPath(new URL("./__tests__/stubs/configurator-ui.txt", import.meta.url)),
      },
    ],
  },
});
