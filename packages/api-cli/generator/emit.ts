// The `cf-os api` command generator: turns the Workshop API's capnweb-schema (`packages/api-schema`,
// extracted from `packages/workshop-shared/src/api.ts` by `pnpm api-schema:generate`, whose script
// calls generate() and writes the files) into the command table, `generated/commands.ts`, and copies
// the agent declarations beside it, `generated/agent-types.ts`, for `cf-os api types`.
//
// Pure, in the shape of a forge plugin: `generate(schema, agent, apps)` returns the files and touches
// nothing. No `node:` imports, no file system, clock or environment. Every decision the CLI makes
// about a method -- its command name, which parameters are positional and which are flags, how each
// is encoded, what its result does to the chain -- is made here, once, and written into the table,
// so the runtime holds no per-method knowledge.
//
// It reads services' methods only: a service's `properties`, which a stub reads by pipelining, are
// no commands, since the CLI calls methods. The one property it reads is of a result: a capability
// held in a top-level property of an object a method returns (`getGatekeeperApp`'s `ui`), which the
// chain may go on to, pipelined on that result, and whose doc an untyped one keeps for its help.
// Nor does it read `format`, `deprecated` or `mutates`, and `direction` only to leave out an
// optional capability the server implements, so the CLI's own fixture, which records none of those,
// builds a table as a full schema does. Of the docs the schema keeps on named types and object
// properties, it reads a named type's, for the help of an argument declared as one, and of their
// tags `@secret` ({@link SECRET_TAG}), to record where a JSON argument holds a secret; the shapes
// it copies into the table, which the runtime revives JSON against, go without them. Of a method's
// tags it reads `@reportsId` ({@link REPORTS_ID_TAG}), which it turns into the command's
// `reportsId`, `@nullWhen` ({@link NULL_WHEN_TAG}), which it turns into the command's `nullWhen`,
// and `@appApi` ({@link APP_API_TAG}), which it turns into a capability property's `byArgument`,
// each left out of the command's doc.
//
// The gatekeeper app UIs (`AppApi`) are schemas of their own, one per gatekeeper whose package.json
// names its app UI's interface, each built into the table as the API's own schema is, from that
// interface, and prefixed with the gatekeeper's vendor id (`context:ContextApi`), nodes, callbacks
// and shapes alike, so that none can collide with the API's or another gatekeeper's. A method tagged
// `@appApi` types its result's untyped capability property by its argument: the generator fills
// that map from these, so the runtime never names a vendor.

