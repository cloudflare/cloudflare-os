/**
 * The agent declarations: the whole file, and the same split per service, by service name; and the
 * declarations of each gatekeeper app UI ({@link AppApi}), by vendor id.
 */
export interface AgentTypes {
  declarations: string;
  fragments: Record<string, string>;
  apps?: Record<string, string>;
}

/**
 * A gatekeeper's app UI: the gatekeeper's vendor id (its `GATEKEEPER_<VENDOR>` binding's suffix,
 * lowercased), and the schema of the interface its `src/app-api.ts` exports as `AppApi`, extracted
 * with that interface as the entry.
 */
export interface AppApi {
  vendor: string;
  schema: Schema;
}

/**
 * `PublicApi`'s credential methods. The session performs them itself, from env or cloudflared, so
 * no secret ever comes from argv; they are not commands.
 */
export const CREDENTIAL_METHODS = ["authenticate", "authenticateFromCfAccess", "createAccount", "login"];

/**
 * The root's methods that take password hashes, which the CLI could only take from argv (or a file
 * written for the purpose): not commands either.
 */
export const ROOT_CREDENTIAL_METHODS = ["changePassword"];

/**
 * The JSDoc tag, on an object property or a named type in api.ts, that marks its value secret:
 * recorded in the table as {@link ApiArg.secrets}, so `--dry-run` prints it redacted.
 */
export const SECRET_TAG = "secret";

/**
 * The JSDoc tag, `@reportsId <noun> <method>().<property>`, on a method in api.ts returning a
 * capability to what it creates: `method()` of that capability, taking no arguments, reads an object
 * whose `property`, a string or a number, is the id of what was created, called `noun`. Recorded as
 * {@link ApiCommand.reportsId}, so the runtime prints the id of what a chain made.
 */
export const REPORTS_ID_TAG = "reportsId";

/**
 * The JSDoc tag, `@nullWhen <text>`, on a method in api.ts whose null result stops a chain (a
 * capability, or a value holding capabilities, that may be null): `text` says when it is null, a
 * clause that may name the next step as a method (`amIAdmin()`). Recorded, in the CLI's words
 * ({@link cliDoc}), as {@link ApiCommand.nullWhen}, which the runtime prints when the chain stops
 * there.
 */
export const NULL_WHEN_TAG = "nullWhen";

/**
 * The JSDoc tag, `@appApi <property> <param>`, on a method in api.ts whose result holds, in its
 * property `property`, the untyped app UI capability of the gatekeeper whose vendor id is the
 * method's required string parameter `param`. Recorded as that capability property's `byArgument`,
 * mapping each {@link AppApi}'s vendor id to its interface's node, so `<command> <vendor> <property>`
 * goes on with that interface's commands.
 */
export const APP_API_TAG = "appApi";

/** The credential method whose result is the table's root. */
const AUTHENTICATE = "authenticate";

/**
 * Words the CLI takes in a command's place on the root: `public` selects the public node, `search`
 * finds commands, `types` prints the agent declarations, `create-account` creates a password account
 * (src/create-account.ts). The root may have no command named any of them.
 */
const RESERVED_COMMANDS = [PUBLIC_SEGMENT, "search", "types", "create-account"];

/**
 * Flags the runtime itself takes, and cloudflare-os-starter's global ones (`--config`, `--account`,
 * `--profile`), which its `cf-os` takes out of the tokens before it runs this CLI. An optional
 * parameter whose flag would be one of these is given as `--arg-<name>` instead.
 */
export const RESERVED_FLAGS = ["account", "answer", "auth", "config", "dry-run", "help", "out", "profile", "timeout",
  "url", "username"];

/** Every generated file: the command table for `schema` and `apps`, and `agent`'s declarations. */
export function generate(schema: Schema, agent: AgentTypes, apps: AppApi[] = []): File[] {
  return [
    { path: COMMANDS_PATH, contents: renderTable(buildTable(schema, apps)) },
    { path: AGENT_TYPES_PATH, contents: renderAgentTypes(agent) },
  ];
}

/** `getChatHistory` as `get-chat-history`, `amIAdmin` as `am-i-admin`. */
export function kebab(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Z])([A-Z][a-z])/g, "$1-$2").replace(/_/g, "-")
    .toLowerCase();
}

/**
 * The command table for `schema`, and for the gatekeeper app UIs `apps`, each prefixed with its
 * vendor id. Throws naming the methods behind any ambiguity.
 */
export function buildTable(schema: Schema, apps: AppApi[] = []): ApiTable {
  const publicService = service(schema, schema.entry, "the entry");
  const authenticate = publicService.methods.find((method) => method.name === AUTHENTICATE);
  const root = authenticate && deref(schema, authenticate.returns);
  if (root?.kind !== "stub" || !root.service) {
    throw new Error(`${schema.entry}.${AUTHENTICATE}() does not return a capability, so there is no root`);
  }
  const salt = schema.constants.SERVICE_SALT;
  if (!salt) throw new Error("no SERVICE_SALT constant");

  const appNodes: Record<string, string> = {};
  for (const app of apps.toSorted((a, b) => compare(a.vendor, b.vendor))) {
    if (!/^[a-z0-9_]+$/.test(app.vendor)) throw new Error(`gatekeeper app "${app.vendor}": a vendor id is lowercase letters, digits and _`);
    if (appNodes[app.vendor]) throw new Error(`gatekeeper app "${app.vendor}" is given twice`);
    appNodes[app.vendor] = prefixedName(app.vendor, app.schema.entry);
  }
  const api = buildGraph(schema, [root.service, schema.entry], (name) =>
    name === schema.entry ? CREDENTIAL_METHODS : name === root.service ? ROOT_CREDENTIAL_METHODS : [], appNodes);
  for (const reserved of RESERVED_COMMANDS) {
    if (api.nodes[root.service]!.commands[reserved]) {
      throw new Error(`${root.service} has a method named "${reserved}", a word the CLI reserves`);
    }
  }
  const graphs = [api, ...apps.map((app) => prefixed(app.vendor, buildGraph(app.schema, [app.schema.entry], () => [], {})))];
  // A prefixed name has a `:`, which no TypeScript name has, so no two graphs share one.
  const merged = <K extends keyof Graph>(part: K): Graph[K] =>
    sortRecord(Object.fromEntries(graphs.flatMap((graph) => Object.entries(graph[part])))) as Graph[K];

  return {
    root: root.service,
    public: schema.entry,
    constants: { SERVICE_SALT: salt },
    nodes: merged("nodes"),
    callbacks: merged("callbacks"),
    shapes: merged("shapes"),
  };
}

/** The nodes, callbacks and shapes of one schema, as the table holds them. */
interface Graph {
  nodes: Record<string, ApiNode>;
  callbacks: Record<string, ApiCallback>;
  shapes: Record<string, ApiShape>;
}

/**
 * The nodes reachable in `schema` from `starts`, each less the methods `omitted` names for it, in the
 * CLI's words, with the callbacks they take and the shapes their arguments and callback answers
 * refer to. `apps` is what an `@appApi` method's capability property is typed as, by vendor id.
 */
function buildGraph(schema: Schema, starts: string[], omitted: (name: string) => string[],
  apps: Record<string, string>): Graph {
  const nodes: Record<string, ApiNode> = {};
  const callbacks: Record<string, ApiCallback> = {};
  const queue = [...starts];
  while (queue.length > 0) {
    const name = queue.shift()!;
    if (nodes[name]) continue;
    const node = buildNode(schema, name, callbacks, omitted(name), apps);
    nodes[name] = node;
    for (const { returns } of Object.values(node.commands)) {
      if (returns.kind === "stub") queue.push(returns.node);
      // A capability in a value result's property is reached as a command's result is.
      if (returns.kind === "value") {
        for (const capability of Object.values(returns.capabilities ?? {})) {
          if (capability.returns.kind === "stub") queue.push(capability.returns.node);
        }
      }
    }
  }

  inCliWords(nodes, callbacks);

  const shapes: Record<string, ApiShape> = {};
  // The shapes the runtime revives against: json arguments' and callback answers'.
  const pending = [...refs([
    ...Object.values(nodes).flatMap((node) =>
      Object.values(node.commands).flatMap((command) => command.args.map((arg) => arg.shape))),
    ...Object.values(callbacks).flatMap((callback) => callback.methods.map((method) => method.answer?.shape)),
  ])];
  while (pending.length > 0) {
    const name = pending.shift()!;
    if (shapes[name]) continue;
    const shape = schema.shapes[name];
    if (!shape) throw new Error(`no shape ${name}`);
    shapes[name] = withoutDocs(shape);
    pending.push(...refs([shape]));
  }
  return { nodes, callbacks, shapes };
}

/** A gatekeeper app UI's name for `name`, one of its interfaces or types, in the table. */
function prefixedName(vendor: string, name: string): string {
  return `${vendor}:${name}`;
}

/**
 * `graph`, a gatekeeper app UI's, with every node, callback and shape named {@link prefixedName}, and
 * so every reference to one; the type texts help prints keep the gatekeeper's own names.
 */
function prefixed(vendor: string, graph: Graph): Graph {
  const name = (of: string) => prefixedName(vendor, of);
  const shape = (value: ApiShape): ApiShape => renamedRefs(value, name);
  const returns = <T extends ApiReturn | ApiCapabilityProperty["returns"]>(result: T): T =>
    result.kind === "stub" ? { ...result, node: name(result.node) } : result;
  const rename = <T>(record: Record<string, T>, value: (item: T) => T) =>
    Object.fromEntries(Object.entries(record).map(([key, item]) => [name(key), value(item)]));
  return {
    nodes: rename(graph.nodes, (node) => ({
      ...node,
      commands: Object.fromEntries(Object.entries(node.commands).map(([command, entry]) => [command, {
        ...entry,
        args: entry.args.map((arg) => ({
          ...arg, ...arg.shape ? { shape: shape(arg.shape) } : {}, ...arg.callback ? { callback: name(arg.callback) } : {},
        })),
        returns: entry.returns.kind === "value" && entry.returns.capabilities
          ? {
            ...entry.returns,
            capabilities: Object.fromEntries(Object.entries(entry.returns.capabilities).map(([key, capability]) =>
              [key, { ...capability, returns: returns(capability.returns) }])),
          }
          : returns(entry.returns),
      }])),
    })),
    callbacks: rename(graph.callbacks, (callback) => ({
      ...callback,
      methods: callback.methods.map((method) => method.answer ? { ...method, answer: { ...method.answer, shape: shape(method.answer.shape) } } : method),
    })),
    shapes: rename(graph.shapes, shape),
  };
}

/** `shape` with every `ref`'s name, at any depth, `name`d. */
function renamedRefs(shape: ApiShape, name: (of: string) => string): ApiShape {
  const walk = (value: unknown): unknown => {
    if (Array.isArray(value)) return value.map(walk);
    if (!value || typeof value !== "object") return value;
    const record = value as Record<string, unknown>;
    if (record.kind === "ref" && typeof record.name === "string") return { ...record, name: name(record.name) };
    return Object.fromEntries(Object.entries(record).map(([key, item]) => [key, walk(item)]));
  };
  return walk(shape) as ApiShape;
}

/** Rewrites every doc in `nodes` and `callbacks` with {@link cliDoc}, against `nodes`' commands. */
function inCliWords(nodes: Record<string, ApiNode>, callbacks: Record<string, ApiCallback>): void {
  const commands: CommandsByNode = new Map(Object.entries(nodes).map(([name, node]) =>
    [name, new Map(Object.entries(node.commands).map(([command, { method }]) => [method, command]))]));
  for (const [name, node] of Object.entries(nodes)) {
    node.doc = cliDoc(node.doc, commands, name);
    for (const command of Object.values(node.commands)) {
      command.doc = cliDoc(command.doc, commands, name);
      if (command.nullWhen) command.nullWhen = cliDoc(command.nullWhen, commands, name);
      for (const arg of command.args) {
        arg.doc = cliDoc(arg.doc, commands, name);
        // Recorded whole by buildArg; the table keeps the first sentence.
        for (const [type, doc] of Object.entries(arg.typeDocs ?? {})) {
          arg.typeDocs![type] = firstSentence(cliDoc(doc, commands, name));
        }
      }
      if (command.returns.kind === "value") {
        for (const capability of Object.values(command.returns.capabilities ?? {})) {
          if (capability.doc) capability.doc = cliDoc(capability.doc, commands, name);
        }
      }
    }
  }
  for (const callback of Object.values(callbacks)) {
    callback.doc = cliDoc(callback.doc, commands);
    for (const method of callback.methods) method.doc = cliDoc(method.doc, commands);
  }
}

/** Each node's commands, by the method they call. */
export type CommandsByNode = Map<string, Map<string, string>>;

/**
 * `doc` in the CLI's words: a method named as `method()` or `Interface.method()` becomes the command
 * that calls it, `` `kebab-name` ``, and paragraphs that start with `TODO`, notes for api.ts's
 * maintainers, are left out. A command on another node than `on`, the one the doc describes, says
 * which (`` `bind` (on GadgetClient) ``), as does an unqualified one only another node has. A code
 * span is rewritten only when it is the call alone: one holding more is code, left as it is.
 */
export function cliDoc(doc: string, commands: CommandsByNode, on?: string): string {
  const named = (match: string, owner: string | undefined, method: string): string => {
    const owners = owner ? [owner] : on && commands.get(on)?.has(method) ? [on]
      : [...commands].filter(([, methods]) => methods.has(method)).map(([name]) => name);
    const command = owners.length > 0 ? commands.get(owners[0]!)?.get(method) : undefined;
    if (!command) return match;
    return owners.length === 1 && owners[0] !== on ? `\`${command}\` (on ${owners[0]})` : `\`${command}\``;
  };
  const call = "(?:([A-Z]\\w*)\\.)?([a-z]\\w*)\\(\\)";
  // Code spans pair within a paragraph, so a stray backtick in one leaves the next alone; they land
  // on the odd indices.
  return doc.split(/\n[ \t]*\n/).filter((paragraph) => !/^\s*TODO\b/.test(paragraph))
    .map((paragraph) => paragraph.split(/(`[^`]*`)/).map((part, index) => index % 2 === 1
      ? part.replace(new RegExp(`^\`${call}\`$`), named)
      : part.replace(new RegExp(`(?<![\\w.\`])${call}(?!\`)`, "g"), named)).join(""))
    .join("\n\n");
}

function service(schema: Schema, name: string, what: string) {
  const found = schema.services[name];
  if (!found) throw new Error(`no service ${name} (${what})`);
  return found;
}

function buildNode(schema: Schema, name: string, callbacks: Record<string, ApiCallback>, omitted: string[],
  apps: Record<string, string>): ApiNode {
  const commands: Record<string, ApiCommand> = {};
  const methodOf: Record<string, string> = {};
  for (const method of service(schema, name, "a stub's").methods) {
    if (omitted.includes(method.name)) continue;
    const command = kebab(method.name);
    if (methodOf[command]) {
      throw new Error(`${name}.${methodOf[command]} and ${name}.${method.name} are both the command "${command}"`);
    }
    methodOf[command] = method.name;
    commands[command] = buildCommand(schema, `${name}.${method.name}`, method, callbacks, apps);
  }
  return { doc: service(schema, name, "a stub's").doc, commands: sortRecord(commands) };
}

function buildCommand(schema: Schema, where: string, method: SchemaMethod,
  callbacks: Record<string, ApiCallback>, apps: Record<string, string>): ApiCommand {
  const args: ApiArg[] = [];
  const paramOf: Record<string, string> = {};
  method.params.forEach((param, index) => {
    const arg = buildArg(schema, `${where}(${param.name})`, param, index, callbacks);
    if (!arg) return;
    if (arg.flag) {
      if (paramOf[arg.flag]) {
        throw new Error(`${where}: parameters ${paramOf[arg.flag]} and ${param.name} are both --${arg.flag}`);
      }
      paramOf[arg.flag] = param.name;
    }
    args.push(arg);
  });
  const returns = buildReturn(schema, where, method, args, callbacks);
  const reportsId = reportsIdOf(schema, where, method, returns);
  const nullWhen = nullWhenOf(where, method, returns);
  const appApi = typeAppApi(where, method, args, returns, apps);
  let doc = reportsId ? withoutTag(method.doc, REPORTS_ID_TAG) : method.doc;
  if (nullWhen) doc = withoutTag(doc, NULL_WHEN_TAG);
  if (appApi) doc = withoutTag(doc, APP_API_TAG);
  return { method: method.name, doc, args, returns, ...reportsId ? { reportsId } : {}, ...nullWhen ? { nullWhen } : {} };
}

/**
 * The method's {@link NULL_WHEN_TAG} text, on one line, checked against what it returns: a null
 * that stops a chain, a nullable capability or a nullable value holding capabilities.
 */
function nullWhenOf(where: string, method: SchemaMethod, returns: ApiReturn): string | undefined {
  const text = method.tags?.[NULL_WHEN_TAG]?.replace(/\s+/g, " ").trim();
  if (text === undefined) return undefined;
  if (!text) throw new Error(`${where}: @${NULL_WHEN_TAG} needs the text of when it returns null`);
  const stops = returns.kind === "stub" ? returns.nullable
    : returns.kind === "value" && returns.nullable === true && returns.capabilities !== undefined;
  if (!stops) {
    throw new Error(`${where}: @${NULL_WHEN_TAG} on a method whose null stops no chain: it returns no capability, ` +
      "nor a value holding one, that may be null");
  }
  return text;
}

/**
 * Applies the method's {@link APP_API_TAG}, checked against its parameters and result, to the
 * capability property it names: its `byArgument` maps `apps`' vendor ids to their nodes (none when
 * there are no apps). Returns whether the method has the tag.
 */
function typeAppApi(where: string, method: SchemaMethod, args: ApiArg[], returns: ApiReturn,
  apps: Record<string, string>): boolean {
  const text = method.tags?.[APP_API_TAG];
  if (text === undefined) return false;
  const match = /^([A-Za-z_$][\w$]*)\s+([A-Za-z_$][\w$]*)$/.exec(text);
  if (!match) throw new Error(`${where}: @${APP_API_TAG} needs "<property> <param>", not "${text}"`);
  const [, property, param] = match as unknown as [string, string, string];
  const capability = returns.kind === "value"
    ? Object.values(returns.capabilities ?? {}).find((candidate) => candidate.property === property) : undefined;
  if (capability?.returns.kind !== "untyped") {
    throw new Error(`${where}: @${APP_API_TAG} names ${property}, no untyped capability property of its result`);
  }
  const arg = args.find((candidate) => candidate.name === param);
  if (!arg || arg.flag || arg.encoding !== "string" || arg.choices) {
    throw new Error(`${where}: @${APP_API_TAG} names ${param}, no required string parameter of it`);
  }
  if (Object.keys(apps).length > 0) capability.byArgument = { index: arg.index, nodes: apps };
  return true;
}

/**
 * The method's {@link REPORTS_ID_TAG}, checked against what it returns: a capability, one of whose
 * methods, taking no arguments, reads an object with the id in a string or number property.
 */
function reportsIdOf(schema: Schema, where: string, method: SchemaMethod, returns: ApiReturn): ApiReportsId | undefined {
  const text = method.tags?.[REPORTS_ID_TAG];
  if (text === undefined) return undefined;
  const match = /^(\S(?:.*\S)?)\s+([A-Za-z_$][\w$]*)\(\)\.([A-Za-z_$][\w$]*)$/.exec(text);
  if (!match) throw new Error(`${where}: @${REPORTS_ID_TAG} needs "<noun> <method>().<property>", not "${text}"`);
  const [, noun, getter, property] = match as unknown as [string, string, string, string];
  if (returns.kind !== "stub") throw new Error(`${where}: @${REPORTS_ID_TAG} on a method that returns no capability`);
  const read = service(schema, returns.node, `${where}'s result`).methods.find((candidate) => candidate.name === getter);
  if (!read || read.params.some((param) => !param.optional)) {
    throw new Error(`${where}: @${REPORTS_ID_TAG} names ${returns.node}.${getter}, no method of it that takes no arguments`);
  }
  const { branches } = present(schema, read.returns);
  const object = branches.length === 1 && branches[0]!.kind === "object" ? branches[0] : undefined;
  const id = object && Object.hasOwn(object.properties, property) ? deref(schema, object.properties[property]!).kind : undefined;
  if (id !== "string" && id !== "number") {
    throw new Error(`${where}: @${REPORTS_ID_TAG} names ${returns.node}.${getter}().${property}, which is no string or number`);
  }
  return { noun, method: getter, property };
}

/**
 * `doc` without the JSDoc tag `name`, which the table records in a field of its own: its line, and
 * the lines its text runs on to, up to the next tag's.
 */
function withoutTag(doc: string, name: string): string {
  let inTag = false;
  return doc.split("\n").filter((line) => {
    if (line.startsWith("@")) inTag = line.startsWith(`@${name} `) || line === `@${name}`;
    return !inTag;
  }).join("\n").trim();
}

/**
 * The parameter as an argument, or undefined for one that is never passed: an optional function, or
 * an optional capability the CLI cannot answer the server's questions through ({@link answerable}).
 */
function buildArg(schema: Schema, where: string, param: SchemaParam, index: number,
  callbacks: Record<string, ApiCallback>): ApiArg | undefined {
  const base = { name: param.name, index };
  const typeDocs = Object.fromEntries(namedParts(param.type).flatMap((name) => {
    const doc = schema.shapes[name]?.doc;
    return doc ? [[name, doc]] : [];
  }));
  const tail = {
    type: typeText(param.type), doc: param.doc, ...Object.keys(typeDocs).length ? { typeDocs } : {},
  };
  const type = deref(schema, param.type);
  if (type.kind === "function") {
    if (param.optional) return undefined;
    if (!isNothing(schema, type.returns)) {
      throw new Error(`${where}: a function returning a value, which the CLI cannot answer`);
    }
    return { ...base, encoding: "function", params: type.params.map((p) => p.name), ...tail };
  }
  if (type.kind === "stub") {
    if (!type.service) {
      if (param.optional) return undefined;
      throw new Error(`${where}: an untyped capability, which the CLI cannot implement`);
    }
    // An optional callback is passed when the server may ask it for a value (openWorkspace's
    // configureObservers: without one, the server refuses to ask). One that only receives events
    // would turn the command into a subscription, and an optional capability the server implements
    // (or one whose methods return what JSON cannot answer) is the server's to fill, so each stays
    // out, and out of the table, without being built.
    if (param.optional && !answerable(schema, type.service)) return undefined;
    const callback = callbacks[type.service] ?? buildCallback(schema, type.service, `${where}'s callback`);
    callbacks[type.service] = callback;
    return { ...base, encoding: "callback", callback: type.service, ...tail };
  }
  if (type.kind === "writableStream") throw new Error(`${where}: a WritableStream, which the CLI cannot provide`);

  const flag = param.optional ? { flag: flagFor(param.name) } : {};
  const direct = scalar(schema, type);
  if (direct) return { ...base, ...flag, ...direct, ...tail };
  if (type.kind === "union") {
    const rest = type.branches.filter((branch) => branch.kind !== "null" && branch.kind !== "undefined");
    const inner = rest.length === 1 ? rest[0]! : { kind: "union" as const, branches: rest };
    const nullable = rest.length < type.branches.length ? scalar(schema, inner) : undefined;
    if (nullable && nullable.encoding !== "stream") {
      return {
        ...base, ...flag, ...nullable, ...(type.branches.some((b) => b.kind === "null") ? { nullable: true } : {}),
        ...tail,
      };
    }
  }
  const secrets = secretPaths(schema, param.type);
  return {
    ...base, ...flag, encoding: "json", shape: withoutDocs(param.type), ...tail, type: spelledTypeText(schema, param.type),
    ...secrets.length ? { secrets } : {},
  };
}

/**
 * Where a value of the `declared` type may hold a secret: the path to each object property, and each value of a
 * named type, marked {@link SECRET_TAG}, through objects, unions, collections and named types, sorted
 * and without a path inside another. A recursive type's paths cannot all be listed, so where a value
 * of one nests in itself and its type holds a secret, that nested value is a secret whole.
 */
function secretPaths(schema: Schema, declared: ApiShape): SecretPath[] {
  /** Whether a value of the named type may hold a secret. */
  const holds = (name: string): boolean => {
    const found: SecretPath[] = [];
    walk({ kind: "ref", name }, [], new Set(), found, false);
    return found.length > 0;
  };
  /** Adds each path to a secret in `shape` to `found`; a nested recursion counts only when `deep`. */
  const walk = (shape: ApiShape, path: SecretPath, seen: ReadonlySet<string>, found: SecretPath[], deep: boolean): void => {
    const into = (inner: ApiShape, segment: string) => walk(inner, [...path, segment], seen, found, deep);
    switch (shape.kind) {
      case "ref": {
        if (seen.has(shape.name)) {
          if (deep && holds(shape.name)) found.push(path);
          return;
        }
        const named = schema.shapes[shape.name];
        if (!named) throw new Error(`no shape ${shape.name}`);
        if (named.tags?.[SECRET_TAG] !== undefined) found.push(path);
        else walk(named, path, new Set([...seen, shape.name]), found, deep);
        return;
      }
      case "object":
        for (const [name, property] of Object.entries(shape.properties)) {
          if (shape.propertyDocs?.[name]?.tags?.[SECRET_TAG] !== undefined) found.push([...path, name]);
          else into(property, name);
        }
        if (shape.index) into(shape.index, "*");
        return;
      case "union":
        for (const branch of shape.branches) walk(branch, path, seen, found, deep);
        return;
      case "array": case "set":
        into(shape.element, "*");
        return;
      case "tuple":
        for (const element of [...shape.elements, ...shape.rest ? [shape.rest] : []]) into(element, "*");
        return;
      case "map":
        into(shape.value, "*");
        return;
      default:
        return;
    }
  };
  const found: SecretPath[] = [];
  walk(declared, [], new Set(), found, true);
  const unique = [...new Map(found.map((path) => [JSON.stringify(path), path])).values()]
    .toSorted((a, b) => compare(JSON.stringify(a), JSON.stringify(b)));
  return unique.filter((path) => !unique.some((other) =>
    other.length < path.length && other.every((segment, i) => segment === path[i])));
}

/** The longest named type {@link spelledTypeText} spells out: a few lines of help, not a page. */
const SPELLED_MAX = 600;

/**
 * A JSON parameter's or a result's type for help: as declared, with each named object or union it
 * is made of (the type itself, a union's branch, an array's element) spelled out once, so its fields
 * are in the help. One that would run past {@link SPELLED_MAX} stays a name.
 */
function spelledTypeText(schema: Schema, shape: ApiShape): string {
  const names = namedParts(shape).filter((name) => ["object", "union"].includes(schema.shapes[name]?.kind ?? ""));
  const spelled = names.map((name) => `${name} = ${typeText(schema.shapes[name]!)}`)
    .filter((text) => text.length <= SPELLED_MAX);
  if (shape.kind === "ref" && spelled.length === 1) return spelled[0]!;
  return spelled.length === 0 ? typeText(shape) : `${typeText(shape)}, where ${spelled.join(", ")}`;
}

/** The named types `shape` is or is made of, each once: itself, a union's branch, an array's element. */
function namedParts(shape: ApiShape): string[] {
  const parts = shape.kind === "union" ? shape.branches : [shape];
  return [...new Set(parts.map((part) => part.kind === "array" ? part.element : part)
    .flatMap((part) => part.kind === "ref" ? [part.name] : []))];
}

/**
 * `shape` without the docs the schema keeps on a named shape (`doc`, `deprecated`, `tags`) and on an
 * object shape's properties (`propertyDocs`), at any depth: what the runtime revives JSON against.
 */
function withoutDocs(shape: ApiShape): ApiShape {
  const { doc: _doc, deprecated: _deprecated, tags: _tags, ...rest } = shape as SchemaShape;
  return Object.fromEntries(Object.entries(rest).flatMap(([key, value]): [string, unknown][] => {
    if (key === "propertyDocs") return [];
    if (key === "properties") {
      return [[key, Object.fromEntries(Object.entries(value as Record<string, ApiShape>)
        .map(([name, property]) => [name, withoutDocs(property)]))]];
    }
    if (key === "params") {
      return [[key, (value as { type: ApiShape }[]).map((param) => ({ ...param, type: withoutDocs(param.type) }))]];
    }
    if (Array.isArray(value)) return [[key, value.map((item: ApiShape) => withoutDocs(item))]];
    return [[key, value !== null && typeof value === "object" ? withoutDocs(value as ApiShape) : value]];
  })) as ApiShape;
}

function flagFor(name: string): string {
  const flag = kebab(name);
  return RESERVED_FLAGS.includes(flag) ? `arg-${flag}` : flag;
}

/** A scalar encoding (with a string-literal union's choices), or undefined for JSON. */
function scalar(schema: Schema, shape: ApiShape): { encoding: ApiEncoding; choices?: string[] } | undefined {
  const type = deref(schema, shape);
  switch (type.kind) {
    case "string": case "number": case "boolean": case "bigint": case "date": case "bytes":
      return { encoding: type.kind };
    case "readableStream":
      return { encoding: "stream" };
    case "literal":
      return literals([type]);
    case "union":
      return literals(type.branches.map((branch) => deref(schema, branch)));
    default:
      return undefined;
  }
}

function literals(shapes: ApiShape[]): { encoding: ApiEncoding; choices?: string[] } | undefined {
  if (!shapes.every((shape) => shape.kind === "literal")) return undefined;
  const values = shapes.map((shape) => (shape as { value: string | number | boolean }).value);
  if (values.every((value) => typeof value === "string")) {
    return { encoding: "string", choices: values.toSorted() };
  }
  if (values.every((value) => typeof value === "number")) return { encoding: "number" };
  if (values.every((value) => typeof value === "boolean")) return { encoding: "boolean" };
  return undefined;
}

/**
 * What the method's result does. A command taking a function, or a callback with an event method (or
 * no methods at all), is a subscription; one whose callbacks only answer is classified by its result,
 * as any call is, so `open-workspace` still continues the chain on the stub it returns.
 */
function buildReturn(schema: Schema, where: string, method: SchemaMethod, args: ApiArg[],
  callbacks: Record<string, ApiCallback>): ApiReturn {
  if (args.some((arg) => arg.encoding === "function"
    || arg.encoding === "callback" && !answersOnly(callbacks[arg.callback!]!))) {
    return { kind: "subscription" };
  }
  let type = deref(schema, method.returns);
  let nullable = false;
  if (type.kind === "union") {
    const rest = type.branches.filter((branch) => branch.kind !== "null" && branch.kind !== "undefined");
    const only = rest.length === 1 ? deref(schema, rest[0]!) : undefined;
    if (only?.kind === "stub") {
      type = only;
      nullable = true;
    }
  }
  if (type.kind === "stub") {
    if (!type.service) return { kind: "untyped" };
    if (service(schema, type.service, `${method.name}'s result`).methods.length === 0) return { kind: "handle" };
    return { kind: "stub", node: type.service, nullable };
  }
  if (type.kind === "readableStream") return { kind: "stream" };
  // Bytes, or bytes or null, which `--out` writes decoded: decided here, as the runtime reads no type text.
  const { branches } = present(schema, method.returns);
  const bytes = branches.length === 1 && branches[0]!.kind === "bytes";
  return {
    kind: "value", type: spelledTypeText(schema, method.returns), ...bytes ? { bytes: true } : {},
    ...capabilityProperties(schema, where, type),
  };
}

/** `shape`'s branches but `null` and `undefined`, dereferenced, and whether it had any of those. */
function present(schema: Schema, shape: ApiShape): { branches: ApiShape[]; nullable: boolean } {
  const type = deref(schema, shape);
  const all = type.kind === "union" ? type.branches.map((branch) => deref(schema, branch)) : [type];
  const branches = all.filter((branch) => branch.kind !== "null" && branch.kind !== "undefined");
  return { branches, nullable: branches.length < all.length };
}

/**
 * The capabilities a value result holds in its top-level properties, by command-like name, when it
 * is one object, or that or null (`nullable`); none for any other result. Each is classified as a
 * result is: an untyped one is continued with `call`, an empty one (a handle) is no hop, and a
 * typed one's property may be optional or `| null`. Throws for two properties of one kebab-case
 * name, as for two methods.
 */
function capabilityProperties(schema: Schema, where: string,
  result: ApiShape): { nullable?: true; capabilities?: Record<string, ApiCapabilityProperty> } {
  const { branches, nullable } = present(schema, result);
  const object = branches.length === 1 ? branches[0]! : undefined;
  if (object?.kind !== "object") return {};
  const capabilities: Record<string, ApiCapabilityProperty> = {};
  for (const [name, shape] of Object.entries(object.properties).toSorted(([a], [b]) => compare(a, b))) {
    const property = present(schema, shape);
    const stub = property.branches.length === 1 ? property.branches[0]! : undefined;
    if (stub?.kind !== "stub") continue;
    let returns: ApiCapabilityProperty["returns"];
    if (!stub.service) returns = { kind: "untyped" };
    else if (service(schema, stub.service, `${where}'s ${name}`).methods.length === 0) continue;
    else returns = { kind: "stub", node: stub.service, nullable: property.nullable };
    const key = kebab(name);
    if (capabilities[key]) {
      throw new Error(`${where}: its result's properties ${capabilities[key].property} and ${name} are both "${key}"`);
    }
    // An untyped one's doc is all its help can say of what it offers.
    const doc = returns.kind === "untyped" ? object.propertyDocs?.[name]?.doc : undefined;
    capabilities[key] = { property: name, returns, ...doc ? { doc } : {} };
  }
  if (Object.keys(capabilities).length === 0) return {};
  return { ...nullable ? { nullable: true } : {}, capabilities: sortRecord(capabilities) };
}

/** Whether every method of `callback` answers, and it has one: the server only asks it for values. */
function answersOnly(callback: ApiCallback): boolean {
  return callback.methods.length > 0 && callback.methods.every((method) => method.answer);
}

/**
 * Whether the CLI can implement the interface `name` as a callback the server asks for values: not
 * one the schema says the server implements, every method's result answerable with JSON, and some
 * method returning one. An old-format schema, with no `direction`, is judged by its results alone.
 */
function answerable(schema: Schema, name: string): boolean {
  const found = service(schema, name, "a callback");
  if (found.direction === "server") return false;
  const results = found.methods.map((method) => deref(schema, method.returns).kind);
  return results.every((kind) => !UNANSWERABLE.includes(kind))
    && found.methods.some((method) => !isNothing(schema, method.returns));
}

/** The result kinds JSON cannot carry back from a callback: a capability, a function or a stream. */
const UNANSWERABLE: string[] = ["stub", "function", "readableStream", "writableStream"];

/**
 * The callback interface `name`, each method with its `answer` when it returns a value. Throws for a
 * method returning what JSON cannot carry back: a capability, a function or a stream.
 */
function buildCallback(schema: Schema, name: string, where: string): ApiCallback {
  const callback = service(schema, name, where);
  return {
    doc: callback.doc,
    methods: callback.methods.map((method) => {
      const result = deref(schema, method.returns);
      if (UNANSWERABLE.includes(result.kind)) {
        throw new Error(`${name}.${method.name}: returns a ${result.kind}, which the CLI cannot answer with JSON`);
      }
      const secrets = secretPaths(schema, method.returns);
      const answer = isNothing(schema, method.returns) ? {} : {
        answer: {
          shape: withoutDocs(method.returns), type: spelledTypeText(schema, method.returns),
          ...secrets.length ? { secrets } : {},
        },
      };
      return { name: method.name, params: method.params.map((param) => param.name), doc: method.doc, ...answer };
    }).toSorted((a, b) => compare(a.name, b.name)),
  };
}

/** Whether a result is nothing at all: a method or function returning it is called for its effect. */
function isNothing(schema: Schema, shape: ApiShape): boolean {
  const kind = deref(schema, shape).kind;
  return kind === "void" || kind === "undefined";
}

/** A `ref`'s shape; anything else as it is. */
function deref(schema: Schema, shape: ApiShape): ApiShape {
  const seen = new Set<string>();
  while (shape.kind === "ref" && !seen.has(shape.name)) {
    seen.add(shape.name);
    const target = schema.shapes[shape.name];
    if (!target) throw new Error(`no shape ${shape.name}`);
    shape = target;
  }
  return shape;
}

/** The names every `ref` inside `values` refers to. */
function refs(values: unknown[]): Set<string> {
  const names = new Set<string>();
  const walk = (value: unknown): void => {
    if (Array.isArray(value)) value.forEach(walk);
    else if (value && typeof value === "object") {
      const record = value as Record<string, unknown>;
      if (record.kind === "ref" && typeof record.name === "string") names.add(record.name);
      Object.values(record).forEach(walk);
    }
  };
  values.forEach(walk);
  return names;
}

function sortRecord<T>(record: Record<string, T>): Record<string, T> {
  return Object.fromEntries(Object.entries(record).toSorted(([a], [b]) => compare(a, b)));
}

function compare(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

const WIDTH = 110;

/** `commands.ts`: the header, the type import, and the table as one readable literal. */
export function renderTable(table: ApiTable): string {
  return `${HEADER}\nimport type { ApiTable } from "../src/table.ts";\n\n`
    + `/** The \`cf-os api\` command table: every command the Workshop API offers. */\n`
    + `export const table: ApiTable = ${literal(table, "", "export const table: ApiTable = ".length)};\n`;
}

/**
 * A JSON-like value as a TypeScript literal: inline when it fits the line, one entry per line
 * otherwise, and a long multi-line string as one `+`-joined line per source line.
 */
function literal(value: unknown, indent: string, used: number): string {
  const inline = inlineLiteral(value);
  if (inline !== undefined && used + inline.length <= WIDTH) return inline;
  const inner = `${indent}  `;
  if (typeof value === "string") {
    const lines = value.split(/(?<=\n)/);
    if (lines.length === 1) return JSON.stringify(value);
    return `\n${lines.map((line) => `${inner}${JSON.stringify(line)}`).join(" +\n")}`;
  }
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    return `[\n${value.map((item) => `${inner}${literal(item, inner, inner.length)},`).join("\n")}\n${indent}]`;
  }
  const entries = Object.entries(value as Record<string, unknown>).filter(([, item]) => item !== undefined);
  if (entries.length === 0) return "{}";
  return `{\n${entries.map(([key, item]) => {
    const head = `${inner}${propertyKey(key)}: `;
    const text = literal(item, inner, head.length);
    // A multi-line string starts on the next line.
    return text.startsWith("\n") ? `${head.trimEnd()}${text},` : `${head}${text},`;
  }).join("\n")}\n${indent}}`;
}

/** The value on one line, or undefined when it holds a multi-line string. */
function inlineLiteral(value: unknown): string | undefined {
  if (typeof value === "string") return value.includes("\n") ? undefined : JSON.stringify(value);
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (Array.isArray(value)) {
    const items = value.map(inlineLiteral);
    return items.includes(undefined) ? undefined : `[${items.join(", ")}]`;
  }
  if (value && typeof value === "object") {
    const entries = Object.entries(value).filter(([, item]) => item !== undefined);
    if (entries.length === 0) return "{}";
    const items = entries.map(([key, item]) => {
      const text = inlineLiteral(item);
      return text === undefined ? undefined : `${propertyKey(key)}: ${text}`;
    });
    return items.includes(undefined) ? undefined : `{ ${items.join(", ")} }`;
  }
  return JSON.stringify(value);
}

/**
 * `value` as a TypeScript expression: an array of its lines, joined, so that a diff of
 * `agent-types.ts` reads line by line as the declarations' own does.
 */
function linesLiteral(value: string, indent: string): string {
  return `[\n${value.split("\n").map((line) => `${indent}  ${JSON.stringify(line)},\n`).join("")}${indent}].join("\\n")`;
}

/**
 * `agent-types.ts`: the header, then the whole declarations, the fragments by service name, and the
 * gatekeeper app UIs' declarations by vendor id.
 */
export function renderAgentTypes(agent: AgentTypes): string {
  const record = (entries: Record<string, string>) => Object.entries(entries).map(([name, text]) =>
    `  ${/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name)}: ${linesLiteral(text, "  ")},`);
  return [
    AGENT_TYPES_HEADER,
    "",
    "/** What a holder of an `AuthenticatedApi` stub can call, as TypeScript declarations, without the credential methods. */",
    `export const declarations: string = ${linesLiteral(agent.declarations, "")};`,
    "",
    "/** The same declarations per service, each readable on its own, other services referred to by name. */",
    "export const fragments: Record<string, string> = {",
    ...record(agent.fragments),
    "};",
    "",
    "/** Each gatekeeper app UI's declarations, by vendor id: the interface its package.json names, and what it reaches. */",
    "export const apps: Record<string, string> = {",
    ...record(agent.apps ?? {}),
    "};",
    "",
  ].join("\n");
}
