import {writeFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
import {
  getBuiltinModels,
  getBuiltinProviders,
} from "@earendil-works/pi-ai/providers/all";

const outputPath = fileURLToPath(
    new URL("../../workshop-shared/src/openai-compatible-models.ts", import.meta.url));
const compatOutputPath = fileURLToPath(
    new URL("../src/generated/openai-compatible-compat.ts", import.meta.url));

function normalizeBaseUrl(value) {
  const url = new URL(value);
  const pathname = url.pathname.replace(/\/+$/, "");
  url.pathname = pathname.endsWith("/chat/completions")
    ? pathname.slice(0, -"/chat/completions".length) || "/"
    : pathname || "/";
  return url.toString().replace(/\/$/, "");
}

const endpoints = {};
const compatibility = {};
for (const catalogProvider of getBuiltinProviders().toSorted()) {
  for (const model of getBuiltinModels(catalogProvider)) {
    if (model.api !== "openai-completions" || !model.baseUrl) continue;
    const endpoint = normalizeBaseUrl(model.baseUrl);
    const models = endpoints[endpoint] ??= {};
    const entry = [model.name, model.contextWindow, model.maxTokens];
    if (models[model.id] && JSON.stringify(models[model.id]) !== JSON.stringify(entry)) {
      throw new Error(`Conflicting Pi catalog entries for ${endpoint} ${model.id}`);
    }
    models[model.id] = entry;
    (compatibility[endpoint] ??= {})[model.id] = model.compat ?? null;
  }
}

function sortRecords(records) {
  for (const models of Object.values(records)) {
    const sorted = Object.fromEntries(
        Object.entries(models).toSorted(([a], [b]) => a.localeCompare(b)));
    for (const key of Object.keys(models)) delete models[key];
    Object.assign(models, sorted);
  }
}

function formatRecords(records) {
  const formattedEndpoints = Object.entries(records).map(([endpoint, models]) => {
    const entries = Object.entries(models)
        .map(([modelId, value]) => `    ${JSON.stringify(modelId)}: ${JSON.stringify(value)},`)
        .join("\n");
    return `  ${JSON.stringify(endpoint)}: {\n${entries}\n  },`;
  }).join("\n");
  return `{\n${formattedEndpoints}\n}`;
}

sortRecords(endpoints);
sortRecords(compatibility);

const source = `// Generated by packages/workshop-backend/scripts/build-openai-compatible-models.mjs.
// Do not edit by hand.

type CatalogEntry = readonly [name: string, contextWindow: number, outputLimit: number];

const MODELS = ${formatRecords(endpoints)} as const satisfies
    Record<string, Record<string, CatalogEntry>>;

// Metadata needed to configure a model recognized in Pi's OpenAI Completions catalog.
export type OpenAiCompatibleModel = {
  name: string;
  contextWindow: number;
  outputLimit: number;
};

// Find a Pi catalog model by its OpenAI-compatible base URL and model identifier.
export function findOpenAiCompatibleModel(
    baseUrl: string, modelId: string): OpenAiCompatibleModel | undefined {
  let url: URL;
  try {
    url = new URL(baseUrl);
  } catch {
    return;
  }
  const pathname = url.pathname.replace(/\\/+$/, "");
  url.pathname = pathname.endsWith("/chat/completions")
    ? pathname.slice(0, -"/chat/completions".length) || "/"
    : pathname || "/";
  const endpoint = url.toString().replace(/\\/$/, "");
  const entry = (MODELS as Record<string, Record<string, CatalogEntry>>)[endpoint]?.[modelId.trim()];
  if (!entry) return;
  const [name, contextWindow, outputLimit] = entry;
  return {name, contextWindow, outputLimit};
}
`;

writeFileSync(outputPath, source);

writeFileSync(compatOutputPath, `// Generated by scripts/build-openai-compatible-models.mjs. Do not edit.
import type {OpenAICompletionsCompat} from "@earendil-works/pi-ai";

const COMPATIBILITY = ${formatRecords(compatibility)} as const;

export function findOpenAiCompatibleCompat(baseUrl: string, modelId: string)
    : OpenAICompletionsCompat | undefined {
  const compat = (COMPATIBILITY as Record<string,
    Record<string, OpenAICompletionsCompat | null>>)[baseUrl]?.[modelId];
  return compat ?? undefined;
}
`);
